// Generar DataURL a partir de SVG con fondo circular/cuadrado blanco para garantizar máximo contraste y legibilidad
function getIconDataUrl(iconId, bgColor = '#ffffff', shape = 'circle') {
  const icon = QR_ICONS[iconId];
  if (!icon || !icon.svg) return null;

  const bgShape = shape === 'circle'
    ? '<circle cx="256" cy="256" r="248" fill="' + bgColor + '" stroke="#e5e7eb" stroke-width="8"/>'
    : '<rect x="8" y="8" width="496" height="496" rx="90" fill="' + bgColor + '" stroke="#e5e7eb" stroke-width="8"/>';

  const combinedSvg = `
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
      ${bgShape}
      <g transform="translate(102, 102) scale(0.6)">
        ${icon.svg}
      </g>
    </svg>
  `.trim();

  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(combinedSvg);
}
